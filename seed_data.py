def reset_and_seed():
    if os.path.exists(db.DB_PATH):
        os.remove(db.DB_PATH)
    db.init_db()

    main = next((b for b in BOUNDARIES if b["is_main"]), BOUNDARIES[0])
    main_c = centroid(main["polygon"])
    cen = {}
    for b in BOUNDARIES:
        c = centroid(b["polygon"])
        cen[b["code"]] = c
        d = "กลาง" if b["is_main"] else direction_from(main_c, c)
        db.add_station(b["code"], b["name"], d, c[0], c[1], b["is_main"])
    db.set_boundaries(BOUNDARIES)

    sid = {s["code"]: s["station_id"] for s in db.get_stations()}

    def insert(rows, category):
        for i, r in enumerate(rows):
            c = cen.get(r["station"], main_c)
            off = 0.0012 * (i + 1)
            db.add_case(
                category=category, case_number=r["case_number"], station_id=sid[r["station"]],
                crime_type=r["crime_type"], report_date=r["report_date"],
                time_bucket=r.get("time_bucket", ""), area=r.get("area", ""),
                location_detail=r.get("location_detail", ""),
                lat=round(c[0] + off, 6), lng=round(c[1] - off, 6),
                victim_name=r.get("victim_name", ""), damage_amount=r.get("damage_amount", 0),
                weapon=r.get("weapon", ""), severity=r.get("severity", 1),
                mo_description=r.get("mo", ""), indicators=r.get("inds", []))

    insert(CYBER_CASES, "cyber")
    insert(PHYSICAL_CASES, "physical")

    db.add_risk_point("physical", "แยกราชประสงค์", 13.7341, 100.5398, "สูง", "ชุมนุม/ความวุ่นวายบ่อย")
