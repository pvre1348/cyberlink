# ===== ฟังก์ชันช่วย: จุดศูนย์กลาง และ ทิศ =====
def centroid(poly):
    pts = poly[:-1] if len(poly) > 1 and poly[0] == poly[-1] else poly
    lat = sum(p[0] for p in pts) / len(pts)
    lng = sum(p[1] for p in pts) / len(pts)
    return [round(lat, 6), round(lng, 6)]


def direction_from(main_c, c):
    """คืนทิศ 8 ทิศของจุด c เทียบกับศูนย์กลางหลัก main_c"""
    dlat = c[0] - main_c[0]   # +เหนือ
    dlng = c[1] - main_c[1]   # +ตะวันออก
    ns = 1 if dlat > 0.004 else (-1 if dlat < -0.004 else 0)
    ew = 1 if dlng > 0.004 else (-1 if dlng < -0.004 else 0)
    table = {
        (1, 0): "เหนือ", (-1, 0): "ใต้", (0, 1): "ตะวันออก", (0, -1): "ตะวันตก",
        (1, 1): "ตะวันออกเฉียงเหนือ", (1, -1): "ตะวันตกเฉียงเหนือ",
        (-1, 1): "ตะวันออกเฉียงใต้", (-1, -1): "ตะวันตกเฉียงใต้", (0, 0): "กลาง",
    }
    return table[(ns, ew)]


